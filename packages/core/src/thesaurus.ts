// The curated thesaurus: plain data, edited by hand, no model and nothing learned. It answers one question:
// "which other ways do papers write this word?". A word of a search and its variants form one concept block
// (see concepts.ts), and a result matches the block if it contains ANY of them.
//
// Rules for an entry (the same ones docs/methodology.md and CONTRIBUTING.md give):
//  - A variant must be something a paper would write INSTEAD of the term, in the same sense. Narrow, not broad:
//    odor may stand for odour, odorant, olfaction, olfactory and "sense of smell", but NOT for aroma or flavor (those are
//    other things: a food paper about the aroma of apples is not a paper about odor perception) and NOT for the bare word
//    smell (a code smell is a software term: 13 of the first 70 results of a live "How AI understand odor" search were about code smells).
//  - "spelling": a US/UK pair or another plain spelling variant. Works both ways.
//  - "abbreviation": an abbreviation and what it stands for. Works both ways.
//  - "synonym": a tight near-synonym or word form. Works ONE way: the term brings its variants, a variant does not
//    bring the term back (so "machine learning" does not drag in "AI").
//  - An all-capital variant of 2 to 6 letters or digits (AI, ML, CNN) is matched with its capitals exactly, as a whole word.
//  - Keep the note to one line saying why the entry is there.
//  - A term may be a list when several spellings share the same variants.

export type ThesaurusType = "spelling" | "abbreviation" | "synonym";

export interface ThesaurusEntry {
  /** The word or phrase a person types. A list means each of them brings the variants. */
  term: string | readonly string[];
  variants: readonly string[];
  type: ThesaurusType;
  /** One line: why this entry exists. */
  note: string;
}

const spelling = (us: string, uk: string): ThesaurusEntry => ({ term: us, variants: [uk], type: "spelling", note: "US/UK spelling" });
const abbreviation = (short: string, long: string | readonly string[]): ThesaurusEntry => ({
  term: short,
  variants: typeof long === "string" ? [long] : long,
  type: "abbreviation",
  note: "abbreviation and what it stands for",
});
const synonym = (term: string | readonly string[], variants: readonly string[], note: string): ThesaurusEntry => ({ term, variants, type: "synonym", note });

